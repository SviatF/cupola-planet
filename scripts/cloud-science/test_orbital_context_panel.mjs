#!/usr/bin/env node
import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const scene=readFileSync("components/CupolaExperience.tsx","utf8");
const panel=readFileSync("components/OrbitalContextPanel.tsx","utf8");
const css=readFileSync("app/globals.css","utf8");
assert.doesNotMatch(scene,/<section className="right-now panel hud">/);
assert.match(scene,/<OrbitalContextPanel/);
assert.match(scene,/satellite=\{selectedSatellite\}/);
assert.match(scene,/event=\{discoveryFocus\}/);
assert.match(scene,/place=\{selectedPlace/);
assert.match(scene,/currentLocation=\{showCurrentLocationContext/);
assert.match(scene,/sunrise=\{followSunrise/);
assert.match(scene,/mobile satellite=\{selectedSatellite\}/);
assert.match(scene,/onFollowSelected=\{toggleFollowSatellite\}/);
assert.match(scene,/onNextEvent=\{exploreEarthNow\}/);
assert.match(scene,/hasContextFocus/);
assert.match(scene,/location-card-context-active/);
assert.match(scene,/mobile-nav--two/);
assert.match(scene,/mobile-object-sheet/);
assert.match(scene,/setMobilePanel\("now"\)/);
assert.match(scene,/setShowCurrentLocationContext\(true\)/);
for (const layer of ["EarthquakeLayer", "VolcanoLayer", "WildfireLayer", "StormLayer"])
  assert.match(scene,new RegExp("<"+layer+" [^>]*onSelect="),"visible Earth-event markers must open contextual inspector");
assert.match(scene,/onSelectEarthEvent=\{focusEarthEvent\}/);
assert.match(scene,/e\.instanceId \?\? -1/,"fire selection must resolve the clicked GPU instance");
assert.match(panel,/if\(!focusKey\|\|!objectType\)return null/);
assert.match(panel,/data-orbital-context=\{objectType\}/);
assert.match(panel,/data-orbital-expanded=\{expanded\?"true":"false"\}/);
assert.match(panel,/CATEGORY SCHEMATIC · NOT AN EXACT MODEL/);
assert.match(panel,/GROUND TRACK/);
assert.match(panel,/SGP4 PROPAGATION/);
assert.match(panel,/NORAD \{selected\.id\}/);
assert.match(panel,/FOLLOW SATELLITE/);
assert.match(panel,/EST\. ORBIT PERIOD/);
assert.match(panel,/ORBITAL SPEED|>SPEED</);
assert.match(panel,/POSITION SNAPSHOT/);
assert.match(panel,/NO DIRECT TELEMETRY/);
assert.match(panel,/EST\. ORBITS \/ DAY/);
assert.match(panel,/LIGHTNING MODEL/);
assert.match(panel,/LIGHTNING OBSERVED/);
for(const kind of ["EARTHQUAKE","CYCLONE","AURORA","WILDFIRE","VOLCANO"])
 assert.match(panel,new RegExp('"'+kind+'"'));
assert.match(panel,/onPointerDown=\{onStart\}/);
assert.match(panel,/setPointerCapture/);
assert.match(panel,/role="img"/);
assert.doesNotMatch(panel,/<Canvas|new THREE|fetch\(/,"no extra WebGL/network resources");
assert.match(css,/\.orbital-context\.orbital-context-compact/);
assert.match(css,/max-height: min\(66svh, 550px\)/);
assert.match(css,/\.mobile-sheet\.mobile-object-sheet/);
const titleIndex=panel.indexOf('className="orbital-identity"');
const visualIndex=panel.indexOf('{selected && <div className="orbital-compact-preview">');
const metricsIndex=panel.indexOf('className="orbital-compact-metrics"');
assert.ok(titleIndex>=0 && titleIndex<visualIndex && visualIndex<metricsIndex,
  "Selected object's title must precede its full-width illustration and metrics");
assert.match(css,/\.orbital-context-compact \.orbital-compact-preview \{width:100%;/);
assert.match(css,/\.orbital-context-compact \.orbital-compact-preview \.orbital-visual \{width:100%;height:105px;/);
assert.match(panel,/aria-pressed=\{satellite\?followingSatellite:followingStation\}/);
assert.match(css,/\.orbital-context-compact \.orbital-compact-actions button \{/);
assert.match(css,/\.orbital-context-compact \.orbital-compact-actions \.orbital-main-action\[aria-pressed="true"\]/);
assert.match(css,/\.location-card \.location-actions \{[\s\S]*?flex-wrap:wrap;/);
assert.match(css,/\.location-card \{[\s\S]*?max-width:calc\(100vw - 315px\);/);
assert.match(css,/\.telemetry \{[\s\S]*?left:auto;[\s\S]*?right:28px;[\s\S]*?bottom:110px;/);
console.log("PASS: on-demand compact draggable desktop/mobile inspector for satellites, ISS, Earth events, sunrise, places and user-picked location");
